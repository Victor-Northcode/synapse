/// Мастерская: постоянные улучшения — главный сток осколков.
/// Бустеры расходуются, а это остаётся навсегда, поэтому цены высокие
/// и растут с каждым уровнем.
class Upgrade {
  final String key;
  final String icon;
  final int maxLevel;

  /// Цена перехода на уровень n (1-based): base * mul^(n-1).
  final int base;
  final double mul;
  const Upgrade(this.key, this.icon, this.maxLevel, this.base, this.mul);

  int priceFor(int nextLevel) =>
      (base * _pow(mul, nextLevel - 1)).round();

  static double _pow(double a, int b) {
    var r = 1.0;
    for (var i = 0; i < b; i++) {
      r *= a;
    }
    return r;
  }
}

